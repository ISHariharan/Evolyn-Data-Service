-- V3: the activity catalogue - every activity someone can log, with its MET value.
-- Filled by V4 from the 2024 Adult Compendium of Physical Activities.
--
-- MET (metabolic equivalent): how hard an activity is compared with sitting
-- still (1 MET). Calories are estimated as MET x weight (kg) x hours.
--
-- A future Compendium edition is added as new rows with its own edition and the
-- old rows switched off (is_active = false), never edited, so past calculations
-- can always be explained.

CREATE TABLE compendium_headings (
    heading_code varchar(2) NOT NULL,            -- first two digits of an activity code, e.g. 15
    name         varchar(60) NOT NULL,           -- e.g. Sports
    CONSTRAINT compendium_headings_pkey PRIMARY KEY (heading_code)
);

CREATE TABLE activity_definitions (
    activity_definition_id bigint GENERATED BY DEFAULT AS IDENTITY,
    edition                varchar(20) NOT NULL,     -- e.g. 2024_ADULT
    activity_code          varchar(5) NOT NULL,      -- Compendium code, e.g. 15330
    heading_code           varchar(2) NOT NULL,
    met_value              numeric(4,1) NOT NULL,    -- copied exactly from the Compendium
    description            varchar(300) NOT NULL,    -- e.g. Handball, team
    is_active              boolean NOT NULL DEFAULT true,
    CONSTRAINT activity_definitions_pkey PRIMARY KEY (activity_definition_id),
    CONSTRAINT uk_activity_edition_code UNIQUE (edition, activity_code),
    CONSTRAINT fk_activity_heading FOREIGN KEY (heading_code) REFERENCES compendium_headings (heading_code),
    CONSTRAINT ck_activity_met CHECK (met_value > 0)
);
CREATE INDEX idx_activity_definitions_heading ON activity_definitions (heading_code);
